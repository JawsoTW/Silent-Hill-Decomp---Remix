#!/usr/bin/env python3
"""Generate pc_port/src/pc_map_msg_count.c: each map's MAP_MESSAGES[] entry
count. mapMessages carries no length at runtime, and the mod text overrides
(lang_text.c) and the randomizer (addons/remix) both need it. Counted from the
map sources by sh_map_source.msg_count (15 shared common lines + the map's own).

Run from the repo root:  python3 pc_port/tools/gen_map_msg_count.py
"""

import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, "pc_port", "src", "pc_map_msg_count.c")

_spec = importlib.util.spec_from_file_location("sh_map_source", os.path.join(HERE, "sh_map_source.py"))
ms = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ms)


def main():
    L = ['/* SPDX-License-Identifier: GPL-3.0-or-later */',
         '/* GENERATED by pc_port/tools/gen_map_msg_count.py -- do not edit. */',
         '',
         '#include "game.h"',
         '#include "bodyprog/map/map.h"',
         '',
         '/* MAP_MESSAGES[] entry count per map. 0 = the map only extern-declares',
         ' * MAP_MESSAGES (an unused stub). */',
         'static const u8 MAP_MSG_COUNT[] = {']
    for m in ms.MAP_NAMES:
        L.append('    [MapIdx_%s] = %d,' % (m.upper(), ms.msg_count(m)))
    L += ['};',
          '',
          '/* Public: MAP_MESSAGES entry count for a map, 0 when unknown. */',
          'int Pc_MapMsgCount(int mapIdx)',
          '{',
          '    if (mapIdx < 0 || mapIdx >= (int)(sizeof(MAP_MSG_COUNT) / sizeof(MAP_MSG_COUNT[0])))',
          '        return 0;',
          '    return MAP_MSG_COUNT[mapIdx];',
          '}',
          '']
    open(OUT, 'w', newline='\n').write('\n'.join(L))
    print('wrote %s (%d maps)' % (os.path.relpath(OUT, REPO), len(ms.MAP_NAMES)))


if __name__ == '__main__':
    main()
